const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { withXcodeProject } = require('expo/config-plugins');

/**
 * Replaces the ShareViewController that `expo-share-intent` generates with one
 * that never opens the app (share-and-forget).
 *
 * The stock controller stashes the share and opens `mobile://dataUrl=…`, which
 * cold-boots the whole app — splash, auth gate, home's fetches — to raise a
 * sheet the user came to dismiss. Ours writes the link into the App Group and
 * completes. That is the entire job.
 *
 * **It used to upload on a background URLSession**, so the link would reach kebi
 * even if the app was never opened again. On iOS 26.6 that never delivered: the
 * extension had a valid token and the right base url, handed the upload over,
 * and the app was never called back — verified by reading the App Group off the
 * device, where records sat with no outcome. Four attempts (unique session
 * identifiers, rebuilding the session iOS names rather than a hardcoded one,
 * not claiming the session at launch, a Void-returning delegate) did not move
 * it. Queueing has no such moving parts: the app drains it with the same
 * authenticated call the in-app save sheet uses, which demonstrably works.
 *
 * The cost is real and deliberate: nothing leaves the phone until the app is
 * opened. Making a share reach kebi on its own needs `/extract` to answer in a
 * second or two with `pending`, so the extension can finish the request before
 * iOS kills it — no background session required.
 *
 * A config plugin rather than a patch: this is a near-total rewrite of that
 * file, so a patch would conflict with every expo-share-intent release.
 *
 * **Ordering is load-bearing and counter-intuitive.** Both this and
 * expo-share-intent write from `withXcodeProject`, and within a mod phase Expo
 * composes plugins so the *earliest*-registered runs *last*. So this plugin must
 * be listed FIRST in app.json's plugins array to overwrite the file they wrote —
 * listing it after them runs it before them, and their controller wins.
 *
 * The extension is deliberately dumb: it does not parse, send, retry, or
 * interpret. It takes the link and leaves.
 */
const withSilentShare = (config, options = {}) => {
  const appGroup = options.appGroup;
  const extensionName = options.extensionName;
  if (!appGroup || !extensionName) {
    throw new Error(
      'with-silent-share: appGroup and extensionName are required (match the expo-share-intent plugin options)',
    );
  }

  return withXcodeProject(config, (cfg) => {
      const target = path.join(
        cfg.modRequest.platformProjectRoot,
        extensionName,
        'ShareViewController.swift',
      );
      // Fail loudly: a silently skipped write means the app still cold-boots on
      // every share, which looks like a design regression rather than a bug.
      if (!fs.existsSync(target)) {
        throw new Error(
          `with-silent-share: ${target} not found — expo-share-intent must be installed, and this plugin must be listed FIRST in app.json (see the note above on mod ordering).`,
        );
      }
      fs.writeFileSync(target, shareViewController(appGroup), 'utf8');
      wantsFullScreenPresentation(cfg.modRequest.platformProjectRoot, extensionName);
      return cfg;
  });
};

/**
 * Ask for full-screen presentation without the sheet's chrome.
 *
 * A share extension is presented in a UISheetPresentationController whose
 * detents are locked to `.large` — an Apple engineer confirmed on the forums
 * that they cannot be customised, so the sheet cannot be made smaller. This flag
 * is the documented escape hatch: full screen, no dimming, no corner radius, no
 * shadow, and the extension sizes its own content inside that.
 *
 * PlistBuddy rather than a plist library: none is resolvable from here, and
 * iOS prebuild only ever runs on macOS. Delete-then-Add keeps it idempotent
 * across repeated prebuilds.
 */
function wantsFullScreenPresentation(platformProjectRoot, extensionName) {
  const plistPath = path.join(platformProjectRoot, extensionName, 'ShareExtension-Info.plist');
  const key = ':NSExtension:NSExtensionAttributes:NSExtensionActionWantsFullScreenPresentation';
  try {
    execFileSync('/usr/libexec/PlistBuddy', ['-c', `Delete ${key}`, plistPath], { stdio: 'ignore' });
  } catch {
    // Not present yet — that is the normal case on a fresh prebuild.
  }
  execFileSync('/usr/libexec/PlistBuddy', ['-c', `Add ${key} bool true`, plistPath]);
}

/** The whole extension, as it will exist on disk. */
function shareViewController(appGroup) {
  return `import UIKit
import Social
import UniformTypeIdentifiers

/// Share-and-forget: take the link, write it where the app will find it, leave.
///
/// Generated by apps/mobile/plugins/with-silent-share.js — edit that, not this.
/// This file is overwritten on every prebuild.
class ShareViewController: UIViewController {
  private let appGroup = "${appGroup}"
  private let queueKey = "kebi.share.queue"

  /// How long the card stays up. iOS blacks out the host app for this whole
  /// window — it will not let an extension's window go transparent — so this is
  /// as short as it can be while still being readable.
  private let visibleDuration: TimeInterval = 0.6

  private let cardTitle = UILabel()
  private let cardSubtitle = UILabel()

  override func viewDidLoad() {
    super.viewDidLoad()
    // iOS presents this full-screen and opaque, and will not be talked out of
    // it (tried: clearing the view, its superview, the host window, and
    // NSExtensionActionWantsFullScreenPresentation). The screen is ours whether
    // we want it or not, so it is painted deliberately rather than left for iOS
    // to fill.
    view.backgroundColor = UIColor(red: 0.075, green: 0.067, blue: 0.059, alpha: 1)
    buildCard()
    // viewDidLoad, not viewDidAppear: the latter fires only after the
    // presentation animation, which was exactly the window a blank box showed.
    handleShare()
  }

  /// Mascot, message, url — centred on Kebi's own dark field.
  ///
  /// No container: once the whole screen belongs to the extension there is
  /// nothing for a card to separate itself from. Values mirror the design
  /// tokens by hand, since a share extension cannot reach the app's NativeWind
  /// styles.
  private func buildCard() {
    let mascot = UILabel()
    mascot.text = "\u{1F426}"
    mascot.font = .systemFont(ofSize: 46)
    mascot.textAlignment = .center

    // Present continuous, and the ellipsis is doing real work: at this instant
    // the link has been written down and nothing more. "saved" would be a claim
    // we may have to retract in "while you were away".
    cardTitle.text = "saving this\u{2026}"
    cardTitle.font = .systemFont(ofSize: 19, weight: .bold)
    cardTitle.textColor = UIColor(red: 0.961, green: 0.945, blue: 0.918, alpha: 1)
    cardTitle.textAlignment = .center

    cardSubtitle.font = .systemFont(ofSize: 12)
    cardSubtitle.textColor = UIColor(red: 0.604, green: 0.576, blue: 0.541, alpha: 1)
    cardSubtitle.textAlignment = .center
    cardSubtitle.lineBreakMode = .byTruncatingTail

    let stack = UIStackView(arrangedSubviews: [mascot, cardTitle, cardSubtitle])
    stack.axis = .vertical
    stack.alignment = .center
    stack.spacing = 14
    stack.setCustomSpacing(8, after: cardTitle)
    stack.translatesAutoresizingMaskIntoConstraints = false
    view.addSubview(stack)

    NSLayoutConstraint.activate([
      stack.centerXAnchor.constraint(equalTo: view.centerXAnchor),
      // Slightly above true centre — optical centre is where the eye expects it.
      stack.centerYAnchor.constraint(equalTo: view.centerYAnchor, constant: -24),
      stack.leadingAnchor.constraint(greaterThanOrEqualTo: view.leadingAnchor, constant: 28),
      stack.trailingAnchor.constraint(lessThanOrEqualTo: view.trailingAnchor, constant: -28),
    ])
  }

  /// Host + path, scheme stripped — a url reads as somewhere it came from
  /// rather than a protocol.
  private func showReceipt(for raw: String) {
    cardSubtitle.text = raw
      .replacingOccurrences(of: "https://", with: "")
      .replacingOccurrences(of: "http://", with: "")
  }

  private func handleShare() {
    guard let item = extensionContext?.inputItems.first as? NSExtensionItem,
          let attachments = item.attachments, !attachments.isEmpty else {
      return complete()
    }

    // What the host app calls the thing being shared. TikTok passes nothing
    // here, but Instagram and Safari do, and a caption beats a shortlink.
    let caption = item.attributedContentText?.string
      .trimmingCharacters(in: .whitespacesAndNewlines)

    loadSharedText(from: attachments) { [weak self] shared in
      guard let self else { return }
      guard let raw = shared?.trimmingCharacters(in: .whitespacesAndNewlines), !raw.isEmpty else {
        return self.complete()
      }
      self.showReceipt(for: raw)
      self.enqueue(raw, caption: caption)
      self.complete()
    }
  }

  /// First URL wins, else first text. TikTok and Instagram both hand over a URL.
  private func loadSharedText(
    from attachments: [NSItemProvider],
    completion: @escaping (String?) -> Void
  ) {
    let urlType = UTType.url.identifier
    let textType = UTType.plainText.identifier

    if let provider = attachments.first(where: { $0.hasItemConformingToTypeIdentifier(urlType) }) {
      provider.loadItem(forTypeIdentifier: urlType, options: nil) { value, _ in
        if let url = value as? URL {
          completion(url.absoluteString)
        } else if let str = value as? String {
          completion(str)
        } else {
          completion(nil)
        }
      }
      return
    }

    if let provider = attachments.first(where: { $0.hasItemConformingToTypeIdentifier(textType) }) {
      provider.loadItem(forTypeIdentifier: textType, options: nil) { value, _ in
        completion(value as? String)
      }
      return
    }

    completion(nil)
  }

  /// The whole job: append to the queue the app drains on next open.
  private func enqueue(_ rawInput: String, caption: String?) {
    guard let defaults = UserDefaults(suiteName: appGroup) else {
      NSLog("[kebi-share] extension: app group unavailable, link lost")
      return
    }
    var queue = readArray(queueKey, from: defaults)
    var entry: [String: Any] = [
      "raw_input": rawInput,
      "shared_at": Int(Date().timeIntervalSince1970 * 1000),
    ]
    if let caption, !caption.isEmpty { entry["title"] = caption }
    queue.append(entry)
    writeArray(queue, to: queueKey, in: defaults)
    NSLog("[kebi-share] extension: queued, %d waiting", queue.count)
  }

  private func readArray(_ key: String, from defaults: UserDefaults) -> [[String: Any]] {
    guard let raw = defaults.string(forKey: key),
          let data = raw.data(using: .utf8),
          let parsed = try? JSONSerialization.jsonObject(with: data) as? [[String: Any]] else {
      return []
    }
    return parsed
  }

  private func writeArray(_ items: [[String: Any]], to key: String, in defaults: UserDefaults) {
    guard let data = try? JSONSerialization.data(withJSONObject: items),
          let json = String(data: data, encoding: .utf8) else { return }
    defaults.set(json, forKey: key)
  }

  /// Dismiss after the card has had time to be read. The link is already
  /// written down by this point, so the wait costs the save nothing.
  private func complete() {
    DispatchQueue.main.asyncAfter(deadline: .now() + visibleDuration) { [weak self] in
      self?.extensionContext?.completeRequest(returningItems: [], completionHandler: nil)
    }
  }
}
`;
}

module.exports = withSilentShare;
// Exported so the generated Swift can be asserted on without running prebuild —
// string interpolation inside a JS template is easy to break and impossible to
// notice until a device rejects the request.
module.exports.shareViewController = shareViewController;
